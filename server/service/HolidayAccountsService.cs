using be;
using database;
using LinqToDB;

namespace service;

public class HolidayAccountsService
{
    private Database db;

    public HolidayAccountsService(Database db)
    {
        this.db = db;
    }

    public async Task<(LawHolidays law_holidays, AgreedHolidays agreed_holidays)> initialize_users_holidays_accounts(User user)
    {
        // the accounts get the earning period the user's start date falls into (not the start date itself),
        // the user's start date is used only for the first history record (see HolidayHistoryService)
        // with the rules that apply on the user's start date
        var (law_earning_start, law_earning_end, law_usage_start, law_usage_end) =
            HolidayParameters.get_account_dates(HolidayType.FerieEfterFerieloven, user.start_date);
        LawHolidays law_holidays = new LawHolidays(user.id, law_earning_start, law_earning_end, law_usage_start, law_usage_end,
            HolidayType.FerieEfterFerieloven, true, 0, 0);

        var (agreed_earning_start, agreed_earning_end, agreed_usage_start, agreed_usage_end) =
            HolidayParameters.get_account_dates(HolidayType.FerieUge, user.start_date);
        AgreedHolidays agreed_holidays = new AgreedHolidays(user.id, agreed_earning_start, agreed_earning_end, agreed_usage_start, agreed_usage_end,
            HolidayType.FerieUge, true, 0, 0);

        // InsertWithOutputAsync returns the saved rows with the id generated by the db (needed for the history FK)
        LawHolidays saved_law_holidays = await db.law_holidays.InsertWithOutputAsync(law_holidays);
        AgreedHolidays saved_agreed_holidays = await db.agreed_holidays.InsertWithOutputAsync(agreed_holidays);

        return (saved_law_holidays, saved_agreed_holidays);
    }
}
