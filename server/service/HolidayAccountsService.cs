using be;
using database;
using LinqToDB;

namespace service;

public class HolidayAccountsService
{
    private Database db;

    // the dates below are a template of ONE earning period, built for HolidayParameters.REFERENCE_YEAR from parameters.json.
    // for a real account they are moved to the needed year with AddYears (see build_account_dates)

    // weeks 1-5 (FerieEfterFerieloven -> LawHolidays)
    private DateOnly law_earning_period_start;
    private DateOnly law_earning_period_end;
    private DateOnly law_usage_period_start;
    private DateOnly law_usage_period_end;

    // week 6 (FerieUge -> AgreedHolidays)
    private DateOnly agreed_earning_period_start;
    private DateOnly agreed_earning_period_end;
    private DateOnly agreed_usage_period_start;
    private DateOnly agreed_usage_period_end;

    public HolidayAccountsService(Database db)
    {
        this.db = db;

        (law_earning_period_start, law_earning_period_end, law_usage_period_start, law_usage_period_end)
            = HolidayParameters.build_period_dates("weeks1To5");
        (agreed_earning_period_start, agreed_earning_period_end, agreed_usage_period_start, agreed_usage_period_end)
            = HolidayParameters.build_period_dates("week6");
    }

    public async Task<(LawHolidays law_holidays, AgreedHolidays agreed_holidays)> initialize_users_holidays_accounts(User user)
    {
        // the accounts get the earning period the user's start date falls into (not the start date itself),
        // the user's start date is used only for the first history record (see HolidayHistoryService)
        var (law_earning_start, law_earning_end, law_usage_start, law_usage_end) = build_account_dates(
            user.start_date, law_earning_period_start, law_earning_period_end, law_usage_period_start, law_usage_period_end);
        LawHolidays law_holidays = new LawHolidays(user.id, law_earning_start, law_earning_end, law_usage_start, law_usage_end,
            HolidayType.FerieEfterFerieloven, true, 0, 0);

        var (agreed_earning_start, agreed_earning_end, agreed_usage_start, agreed_usage_end) = build_account_dates(
            user.start_date, agreed_earning_period_start, agreed_earning_period_end, agreed_usage_period_start, agreed_usage_period_end);
        AgreedHolidays agreed_holidays = new AgreedHolidays(user.id, agreed_earning_start, agreed_earning_end, agreed_usage_start, agreed_usage_end,
            HolidayType.FerieUge, true, 0, 0);

        // InsertWithOutputAsync returns the saved rows with the id generated by the db (needed for the history FK)
        LawHolidays saved_law_holidays = await db.law_holidays.InsertWithOutputAsync(law_holidays);
        AgreedHolidays saved_agreed_holidays = await db.agreed_holidays.InsertWithOutputAsync(agreed_holidays);

        return (saved_law_holidays, saved_agreed_holidays);
    }

    // moves the template period dates to the earning period that contains the given date
    // example (law, 1 Sep - 31 Aug): 17.11.2026 -> 01.09.2026 - 31.08.2027, 10.03.2026 -> 01.09.2025 - 31.08.2026
    private static (DateOnly earning_start, DateOnly earning_end, DateOnly usage_start, DateOnly usage_end) build_account_dates(
        DateOnly date, DateOnly t_earning_start, DateOnly t_earning_end, DateOnly t_usage_start, DateOnly t_usage_end)
    {
        int years_shift = date.Year - t_earning_start.Year;

        // the earning period of this year has not started yet on that date, so the date belongs to the previous one
        if (t_earning_start.AddYears(years_shift) > date)
        {
            years_shift--;
        }

        return (t_earning_start.AddYears(years_shift),
                t_earning_end.AddYears(years_shift),
                t_usage_start.AddYears(years_shift),
                t_usage_end.AddYears(years_shift));
    }
}
