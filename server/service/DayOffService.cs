using System.Net.Http.Json;
using System.Text.Json.Serialization;
using be;
using database;
using LinqToDB;
using LinqToDB.Async;
using LinqToDB.Data;

namespace service;

public class DayOffService
{
    private Database db;

    // HttpClient for the public holidays API, its base address is set in Program.cs (AddHttpClient<DayOffService>)
    private HttpClient http;

    public DayOffService(Database db, HttpClient http)
    {
        this.db = db;
        this.http = http;
    }

    // --- pipeline 1: company days off entered by the admin ---

    // one company day off from the admin's form. it is always saved as a company day, whatever holiday_type it came with.
    // throws ArgumentException if the date already is a day off (UNIQUE on date)
    public async Task<DayOff> add_company_day_off(DayOff day)
    {
        DayOff? existing = await db.days_off.FirstOrDefaultAsync(d => d.date == day.date);
        if (existing != null)
        {
            throw new ArgumentException($"{day.date:yyyy-MM-dd} already is a day off ({existing.name})");
        }

        day.holiday_type = TypeOfHolidayDay.Company;
        // InsertWithOutputAsync returns the saved row with the id generated by the db
        return await db.days_off.InsertWithOutputAsync(day);
    }

    // all days off (Danish and company) of a year, sorted by date
    public async Task<List<DayOff>> get_days_off(int year)
    {
        DateOnly from = new DateOnly(year, 1, 1);
        DateOnly until = new DateOnly(year, 12, 31);
        return await db.days_off
            .Where(d => d.date >= from && d.date <= until)
            .OrderBy(d => d.date)
            .ToListAsync();
    }

    // --- pipeline 2: Danish public holidays of a year from the Nager.Date API ---

    // one holiday as the API returns it (only the fields we need)
    private class ApiHoliday
    {
        [JsonPropertyName("date")] public DateOnly date { get; set; }
        [JsonPropertyName("localName")] public string local_name { get; set; } = "";
        // "Public" = official day off. Juleaftensdag, Grundlovsdag... are "Bank" / "Optional",
        // they are not public holidays (the company can add them as company days)
        [JsonPropertyName("types")] public List<string> types { get; set; } = new List<string>();
    }

    public async Task<List<DayOff>> add_danish_holidays(int year)
    {
        List<ApiHoliday>? holidays;
        try
        {
            holidays = await http.GetFromJsonAsync<List<ApiHoliday>>($"PublicHolidays/{year}/DK");
        }
        catch (Exception e) when (e is HttpRequestException or TaskCanceledException or System.Text.Json.JsonException)
        {
            throw new InvalidOperationException("The public holidays service is not available, try again later", e);
        }

        if (holidays == null)
        {
            throw new InvalidOperationException("The public holidays service returned no data");
        }

        List<DayOff> days = holidays
            .Where(h => h.types.Contains("Public"))
            .Select(h => new DayOff { name = h.local_name, date = h.date, holiday_type = TypeOfHolidayDay.Danish })
            .ToList();

        return await insert_days_off(days);
    }

    // --- shared by both pipelines ---

    // saves many days off (Danish public holidays or company days) with one batch insert.
    // a date can be a day off only once (UNIQUE on date), so dates that already are days off are skipped
    // instead of failing the whole batch. returns the days that were really inserted
    public async Task<List<DayOff>> insert_days_off(List<DayOff> days_off)
    {
        // the same date twice in the given list: keep the first one
        List<DayOff> unique_days = days_off
            .GroupBy(d => d.date)
            .Select(g => g.First())
            .ToList();

        List<DateOnly> dates = unique_days.Select(d => d.date).ToList();

        // one query for all dates that already are days off
        List<DateOnly> existing_dates = await db.days_off
            .Where(d => dates.Contains(d.date))
            .Select(d => d.date)
            .ToListAsync();

        List<DayOff> new_days = unique_days
            .Where(d => !existing_dates.Contains(d.date))
            .ToList();

        if (new_days.Count == 0)
        {
            return new_days;
        }

        // one batch insert for all new days (id is generated by the db)
        await db.days_off.BulkCopyAsync(new_days);
        return new_days;
    }
}
