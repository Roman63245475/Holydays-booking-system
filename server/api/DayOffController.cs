using be;
using Microsoft.AspNetCore.Mvc;
using service;

namespace api;

// days off that are never counted as holiday: Danish public holidays and company days off.
// only the system owner (Admin) defines them
[ApiController]
public class DayOffController : ControllerBase
{
    private DayOffService dayOffService;

    public DayOffController(DayOffService dayOffService)
    {
        this.dayOffService = dayOffService;
    }

    private bool is_admin()
    {
        return HttpContext.Session.GetString("role") == Role.Admin.ToString();
    }

    // all days off of a year (Danish public holidays and company days), for the admin's Holidays tab and the calendar.
    // any logged in user may read them
    [HttpGet(nameof(get_days_off))]
    public async Task<ActionResult<List<DayOff>>> get_days_off([FromQuery] int year)
    {
        if (HttpContext.Session.GetString("userId") == null)
        {
            return Unauthorized();
        }
        if (year < 2000 || year > 2100)
        {
            return BadRequest("year must be between 2000 and 2100");
        }
        return Ok(await dayOffService.get_days_off(year));
    }

    // pipeline 1: one company day off from the admin's "Add new holiday" form
    [HttpPost(nameof(add_company_days_off))]
    public async Task<ActionResult<DayOff>> add_company_days_off([FromBody] CompanyDayOffDTO day)
    {
        if (!is_admin())
        {
            return StatusCode(StatusCodes.Status403Forbidden, "Only the system owner can add days off");
        }

        string? error = day.validate();
        if (error != null)
        {
            return BadRequest(error);
        }

        try
        {
            // returns the saved day off with the id generated by the db
            return Ok(await dayOffService.add_company_day_off(day.to_day_off()));
        }
        catch (ArgumentException e)
        {
            return BadRequest(e.Message);
        }
    }

    // pipeline 2: Danish public holidays of a year, fetched from the Nager.Date API
    [HttpPost(nameof(add_danish_holidays))]
    public async Task<ActionResult<List<DayOff>>> add_danish_holidays([FromQuery] int year)
    {
        if (!is_admin())
        {
            return StatusCode(StatusCodes.Status403Forbidden, "Only the system owner can add days off");
        }

        if (year < 2000 || year > 2100)
        {
            return BadRequest("year must be between 2000 and 2100");
        }

        try
        {
            return Ok(await dayOffService.add_danish_holidays(year));
        }
        catch (InvalidOperationException e)
        {
            // the external API is down or answered with something unexpected
            return StatusCode(StatusCodes.Status502BadGateway, e.Message);
        }
    }
}
